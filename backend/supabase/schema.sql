-- Initial shared catalogue schema for Supabase/Postgres.
-- Review and run in a new project before enabling production use.
create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_tavish_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users a where a.user_id = auth.uid()
  );
$$;

revoke all on function public.is_tavish_admin() from public;
grant execute on function public.is_tavish_admin() to anon, authenticated;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text not null unique,
  slug text not null unique,
  name text not null,
  category text not null,
  category_slug text not null,
  subcategory text,
  subcategory_slug text,
  description text not null default '',
  material text,
  finish text,
  dimensions text,
  weight text,
  price numeric(12,2) not null check (price > 0),
  sale_price numeric(12,2) check (sale_price is null or sale_price > 0),
  status text not null default 'DRAFT' check (status in ('ACTIVE','DRAFT','HIDDEN','TRASH','OUT_OF_STOCK')),
  availability text not null default 'IN_STOCK' check (availability in ('IN_STOCK','OUT_OF_STOCK')),
  images jsonb not null default '[]'::jsonb check (jsonb_typeof(images) = 'array' and jsonb_array_length(images) between 0 and 4),
  primary_image text,
  tags jsonb not null default '[]'::jsonb check (jsonb_typeof(tags) = 'array'),
  featured boolean not null default false,
  new_arrival boolean not null default false,
  best_seller boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_public_listing_idx
  on public.products (status, category_slug, sort_order);
create index if not exists products_updated_at_idx
  on public.products (updated_at desc);

alter table public.products enable row level security;
alter table public.admin_users enable row level security;

-- Public visitors can read published catalogue items only.
drop policy if exists "Public can read published products" on public.products;
create policy "Public can read published products"
  on public.products for select to anon, authenticated
  using (status in ('ACTIVE','OUT_OF_STOCK'));

-- Authenticated Admins can read drafts and manage catalogue records.
drop policy if exists "Admins can read all products" on public.products;
create policy "Admins can read all products"
  on public.products for select to authenticated
  using (public.is_tavish_admin());
drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products"
  on public.products for insert to authenticated
  with check (public.is_tavish_admin());
drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products"
  on public.products for update to authenticated
  using (public.is_tavish_admin())
  with check (public.is_tavish_admin());
drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products"
  on public.products for delete to authenticated
  using (public.is_tavish_admin());

-- Admin membership is managed by a trusted project owner in the SQL editor.
-- Do not allow public clients to self-assign admin membership.
drop policy if exists "Admins can read own membership" on public.admin_users;
create policy "Admins can read own membership"
  on public.admin_users for select to authenticated
  using (user_id = auth.uid() and public.is_tavish_admin());

-- Note: never place the service_role key in frontend code. Review all policies
